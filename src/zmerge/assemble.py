"""Assemble the docs of all projects into a single, regular Zensical project.

The merged project is written next to the umbrella configuration, so all paths in the umbrella configuration
(``custom_dir``, ``site_dir``, ...) stay valid:

- ``.zmerge/docs/`` holds the umbrella docs and the docs of every project below its prefix.
- ``.zmerge.toml`` is the umbrella configuration with the merged ``nav`` and ``docs_dir``.

Files are hardlinked where possible. A file in the staging directory may share its inode with the source, so it must
never be opened for writing in place; replace it instead.
"""

from __future__ import annotations

import os
import posixpath
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import TYPE_CHECKING, Any

import tomli_w

from zmerge.config import Include, Link, Section, ZmergeError
from zmerge.links import rewrite_links
from zmerge.merge import merge_config

if TYPE_CHECKING:
    from collections.abc import Mapping

    from zmerge.config import NavItem, Project, Site

STAGING_DIR = ".zmerge"
GENERATED_CONFIG = ".zmerge.toml"

_URL = re.compile(r"^(?:[a-zA-Z][a-zA-Z0-9+.-]*:|/|#)")
_INDEX_PAGES = ("index.md", "README.md")


@dataclass(frozen=True)
class Source:
    """A file of the merged docs.

    Attributes:
        path: Absolute path to the source file.
        owner: Prefix of the project the file belongs to, ``""`` for the umbrella site.
    """

    path: Path
    owner: str


@dataclass(frozen=True)
class Assembly:
    """The result of assembling a site.

    Attributes:
        config_file: Path to the generated Zensical configuration.
        docs_dir: Path to the merged docs directory.
        files: Merged files, keyed by their POSIX path relative to ``docs_dir``.
        warnings: Problems that did not prevent the merge, e.g. conflicting options.
    """

    config_file: Path
    docs_dir: Path
    files: Mapping[str, Source]
    warnings: list[str] = field(default_factory=list)


def assemble(site: Site) -> Assembly:
    """Assemble the merged Zensical project of a site.

    Args:
        site: The umbrella site.

    Returns:
        The assembled project.
    """
    staging = site.root / STAGING_DIR
    docs_dir = staging / "docs"
    files = collect_files(site)
    nav = _convert_nav(site.nav, prefix="", files=files, config_file=site.config_file)

    rewritten, link_warnings = rewrite_links(site, files)
    _materialize(files, docs_dir, rewritten)
    (staging / ".gitignore").write_text("*\n", encoding="utf-8")

    config, warnings = merge_config(site)
    warnings += link_warnings
    config["docs_dir"] = docs_dir.relative_to(site.root).as_posix()
    config["nav"] = nav
    config_file = site.root / GENERATED_CONFIG
    config_file.write_text(
        "# Generated by zmerge from {}. Do not edit.\n{}".format(
            site.config_file.name, tomli_w.dumps({"project": config})
        ),
        encoding="utf-8",
    )
    return Assembly(config_file=config_file, docs_dir=docs_dir, files=files, warnings=warnings)


def collect_files(site: Site) -> dict[str, Source]:
    """Collect the files of the umbrella site and all projects.

    Args:
        site: The umbrella site.

    Returns:
        The merged files, keyed by their POSIX path relative to the merged docs directory.

    Raises:
        ZmergeError: If two files end up at the same path.
    """
    files: dict[str, Source] = {}
    sources: list[tuple[str, Path, Path, Mapping[str, Any]]] = [
        ("", site.docs_dir, site.config_file, site.config),
        *((p.prefix, p.docs_dir, p.config_file, p.config) for p in site.projects),
    ]
    for prefix, docs_dir, config_file, config in sources:
        excluded = _excluded_dirs(docs_dir, config_file, config)
        for rel_path, path in _walk(docs_dir, excluded):
            key = posixpath.join(prefix, rel_path) if prefix else rel_path
            if (other := files.get(key)) is not None:
                raise ZmergeError(f"{path} and {other.path} would both be merged to {key!r}; change a prefix")
            files[key] = Source(path=path, owner=prefix)
    return files


def _excluded_dirs(docs_dir: Path, config_file: Path, config: Mapping[str, Any]) -> set[Path]:
    """Return directories inside ``docs_dir`` that are not documentation, e.g. a theme ``custom_dir``."""
    excluded = set()
    if custom_dir := config.get("theme", {}).get("custom_dir"):
        path = (config_file.parent / custom_dir).resolve()
        if path.is_relative_to(docs_dir):
            excluded.add(path)
    return excluded


def _walk(docs_dir: Path, excluded: set[Path]) -> list[tuple[str, Path]]:
    """List the files below ``docs_dir``, skipping hidden entries like Zensical does."""
    found = []
    for dirpath, dirnames, filenames in os.walk(docs_dir, followlinks=True):
        current = Path(dirpath)
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and current / d not in excluded)
        rel_dir = current.relative_to(docs_dir).as_posix()
        for filename in sorted(filenames):
            if not filename.startswith("."):
                rel_path = filename if rel_dir == "." else f"{rel_dir}/{filename}"
                found.append((rel_path, current / filename))
    return found


def _materialize(files: Mapping[str, Source], docs_dir: Path, rewritten: Mapping[str, str]) -> None:
    """Recreate ``docs_dir`` with hardlinks to all files, falling back to copies, and write rewritten files."""
    if docs_dir.exists():
        shutil.rmtree(docs_dir)
    created: set[Path] = set()
    for rel_path, source in files.items():
        target = docs_dir / rel_path
        if target.parent not in created:
            target.parent.mkdir(parents=True, exist_ok=True)
            created.add(target.parent)
        if (text := rewritten.get(rel_path)) is not None:
            target.write_text(text, encoding="utf-8")
            continue
        try:
            os.link(source.path, target)
        except OSError:
            # E.g. the source is on another file system or links are not permitted.
            shutil.copy2(source.path, target)


def _is_url(target: str) -> bool:
    return bool(_URL.match(target))


def _convert_nav(
    items: tuple[NavItem, ...], *, prefix: str, files: Mapping[str, Source], config_file: Path
) -> list[Any]:
    """Convert a nav tree into Zensical's nav format with all page paths relative to the merged docs."""
    nav: list[Any] = []
    for item in items:
        if isinstance(item, Link):
            target = item.target
            if not _is_url(target):
                target = posixpath.normpath(posixpath.join(prefix, target))
                if target not in files:
                    raise ZmergeError(f"{config_file}: nav entry {item.target!r} points to a missing page")
            nav.append(target if item.title is None else {item.title: target})
        elif isinstance(item, Section):
            nav.append({item.title: _convert_nav(item.items, prefix=prefix, files=files, config_file=config_file)})
        else:
            nav.append({item.title: _project_nav(item, files)})
    return nav


def _project_nav(include: Include, files: Mapping[str, Source]) -> list[Any]:
    project: Project = include.project
    if project.nav is not None:
        return _convert_nav(project.nav, prefix=project.prefix, files=files, config_file=project.config_file)
    pages = [path for path, source in files.items() if source.owner == project.prefix and path.endswith(".md")]
    if not pages:
        raise ZmergeError(f"{project.config_file}: project has no pages in {project.docs_dir}")
    return _auto_nav(project.prefix, pages)


def _auto_nav(prefix: str, pages: list[str]) -> list[Any]:
    """Build a nav from the folder structure, mirroring Zensical's behaviour without an explicit nav.

    Pages are listed without titles so Zensical uses their first heading. Index pages come first, followed by the
    remaining pages and folders in alphabetical order.

    Returns:
        The nav in Zensical's format.
    """
    tree: dict[str, Any] = {}
    for page in pages:
        node = tree
        *dirs, name = posixpath.relpath(page, prefix).split("/")
        for directory in dirs:
            node = node.setdefault(directory + "/", {})
        node[name] = page

    def convert(node: dict[str, Any]) -> list[Any]:
        index = [node[name] for name in _INDEX_PAGES if name in node][:1]
        rest = []
        for name in sorted(node, key=lambda n: n.rstrip("/").lower()):
            value = node[name]
            if isinstance(value, dict):
                rest.append({_dir_title(name.rstrip("/")): convert(value)})
            elif value not in index:
                rest.append(value)
        return index + rest

    return convert(tree)


def _dir_title(name: str) -> str:
    """Derive a section title from a folder name like Zensical does, e.g. ``getting_started`` → ``Getting started``."""
    title = re.sub(r"[-_]+", " ", name).strip()
    return title[:1].upper() + title[1:]
